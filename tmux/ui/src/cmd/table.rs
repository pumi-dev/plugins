//! Every built-in command (03 §6): its name, tmux's names for it, tmux's flag template, and what
//! runs it. tmux's templates are from tmux 3.8's `cmd-*.c`; pumi's long forms are added to them.

use pumi_api::{Cx, Result};
use pumi_lang::cmd::{Long, Parsed};

use super::builtin::{
    buffer, command_prompt, confirm_before, hook, key, needs_client, option, pane, pumi, script, server, session,
    style, tab, user,
};
use super::{Flow, Queue};

pub type Exec = fn(&mut Cx, &mut Queue, &Parsed) -> Result<Flow>;

pub struct Entry {
    pub name: &'static str,
    pub aliases: &'static [&'static str],
    /// tmux's `args` template: a letter is a switch, `x:` takes a value, `x::` an optional one.
    pub template: &'static str,
    pub min: i32,
    /// `-1`: any number.
    pub max: i32,
    pub usage: &'static str,
    pub desc: &'static str,
    pub longs: &'static [(&'static str, Long)],
    /// Its arguments are its own: no flags are read (`call`, `autocmd`, Neovim's `command`).
    pub raw: bool,
    pub exec: Exec,
}

#[allow(clippy::too_many_arguments)]
const fn e(
    name: &'static str,
    aliases: &'static [&'static str],
    template: &'static str,
    min: i32,
    max: i32,
    usage: &'static str,
    desc: &'static str,
    exec: Exec,
) -> Entry {
    Entry { name, aliases, template, min, max, usage, desc, longs: &[], raw: false, exec }
}

