// Bundles CodeMirror (`scripts/codemirror.ts`) into `src/vendor/codemirror.js`: one file the
// plugin carries, minified, so it runs without `bun install`. Run it after changing a version.
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const built = await Bun.build({
  entrypoints: [join(root, "scripts/codemirror.ts")],
  target: "bun",
  format: "esm",
  minify: true,
});
if (!built.success) {
  for (const log of built.logs) console.error(log);
  process.exit(1);
}
const banner = "// Generated by `bun scripts/vendor.ts` from CodeMirror 6 (MIT, https://codemirror.net). Do not edit.\n";
const out = join(root, "src/vendor/codemirror.js");
await Bun.write(out, banner + (await built.outputs[0].text()));
console.log(`wrote ${out} (${(Bun.file(out).size / 1024).toFixed(0)} KB)`);
