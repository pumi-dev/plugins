#!/usr/bin/env bun
// The app's workers are a compiled bundle: they resolve a package's own files, not its node_modules.
// So Pele — the Mermaid renderer, `pele` on npm — is written into `src/pele.vendor.js` here, and
// `src/pele.ts` imports that file. Run after `bun install`, and after bumping `pele`.
import { build } from "bun";
import { join, resolve } from "node:path";

const here = resolve(import.meta.dir, "..");
const out = join(here, "src/pele.vendor.js");
const made = await build({
  entrypoints: [join(here, "node_modules/pele/dist/pele.js")],
  target: "bun",
  format: "esm",
  minify: false,
  outdir: join(here, "src"),
  naming: "pele.vendor.js",
});
if (!made.success) {
  for (const log of made.logs) console.error(String(log));
  process.exit(1);
}
const { version } = JSON.parse(await Bun.file(join(here, "node_modules/pele/package.json")).text());
const head = `// Generated by \`bun scripts/vendor-pele.mjs\` from pele@${version} (MIT, kepano). Do not edit:\n// the app's workers resolve a package's own files, not its node_modules, so this file is how\n// Pele — a Mermaid renderer, \`pele\` on npm — reaches the worker.\n`;
const text = await Bun.file(out).text();
await Bun.write(out, head + text);
console.log(`src/pele.vendor.js: pele@${version}, ${(text.length / 1024).toFixed(0)} KB`);
